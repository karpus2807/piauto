def draw_storage_icon(oled, kind, x, y, fill=1):
    icon = STORAGE_ICONS.get(kind, _ICON_SD)
    oled.draw_bitmap(icon, x, y, fill=fill)


def draw_bitmap_scaled(oled, bitmap, x, y, w, h, fill=1):
    native_w = len(bitmap[0])
    native_h = len(bitmap)
    w = max(1, int(w))
    h = max(1, int(h))
    for row in range(h):
        for col in range(w):
            sr = int(row * native_h / h)
            sc = int(col * native_w / w)
            if bitmap[sr][sc]:
                oled.draw.point((x + col, y + row), fill=fill)


def draw_builtin_icon(oled, name, x, y, w=14, h=14, fill=1):
    bitmap = BUILTIN_ICONS.get(str(name).lower(), _ICON_SD)
    # Native icons are 14x14. Old designer builds saved defaults as 16x16,
    # which made nearest-neighbour scaling look fat/broken on SSD1306.
    if int(w) <= 16 and int(h) <= 16:
        oled.draw_bitmap(bitmap, x, y, fill=fill)
    else:
        draw_bitmap_scaled(oled, bitmap, x, y, w, h, fill=fill)
